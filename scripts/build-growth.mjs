import { readFile, writeFile, mkdir } from "node:fs/promises";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const { minify } = require("next/dist/compiled/terser");
const source = await readFile(new URL("./growth-runtime.cjs", import.meta.url), "utf8");
const built = await minify(source, { ecma: 2018, compress: { passes: 2 }, mangle: true, format: { comments: false } });
if (!built.code) throw new Error("Growth runtime minification returned empty output.");
const output = "/*! Can Evim — generated by scripts/build-growth.mjs */\n" + built.code + "\n";
await writeFile(new URL("../public/growth.js", import.meta.url), output);
console.log(`Growth runtime: ${Buffer.byteLength(source)} → ${Buffer.byteLength(output)} bytes`);
const loader = await readFile(new URL("./growth-loader.cjs", import.meta.url), "utf8");
const loaderBuilt = await minify(loader, { ecma: 2018, compress: { passes: 2 }, mangle: true, format: { comments: false } });
if (!loaderBuilt.code) throw new Error("Empty loader output");
await writeFile(new URL("../public/growth-loader.js", import.meta.url), `${loaderBuilt.code}\n`);
const homeUI = await readFile(new URL("./home-ui.cjs", import.meta.url), "utf8");
const homeBuilt = await minify(homeUI, { ecma: 2018, compress: { passes: 2 }, mangle: true, format: { comments: false } });
if (!homeBuilt.code) throw new Error("Empty home UI output");
await writeFile(new URL("../public/home-ui.js", import.meta.url), `${homeBuilt.code}\n`);
await mkdir(new URL("../public/performance/ui/", import.meta.url), { recursive: true });
for (const name of ["interactive", "routes"]) {
  const css = await readFile(new URL(`../app/growth-${name}.css`, import.meta.url), "utf8");
  await writeFile(new URL(`../public/performance/ui/${name}.css`, import.meta.url), css);
}
